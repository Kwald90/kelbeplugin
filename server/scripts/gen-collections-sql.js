// Writes the tenant-table migrations from src/collections.js: 0003_collections.sql for the
// original collections, and one more file per `migration` name for collections added later
// (e.g. 0100_workplan.sql), each creating its tables exactly the same way.
//   node scripts/gen-collections-sql.js          write the files
//   node scripts/gen-collections-sql.js --print  print to stdout
// test/unit.test.js checks the committed files still match this output. A shipped
// migration's collections never change `migration`: new collections get a new name.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { TABLE_COLLECTIONS, collectionDef } from '../src/collections.js';

export const BASE_MIGRATION = '0003_collections';
export const OUT = fileURLToPath(new URL(`../migrations/${BASE_MIGRATION}.sql`, import.meta.url));
const migrationOf = (c) => collectionDef(c).migration || BASE_MIGRATION;

function tableSql(def) {
  const t = def.table;
  const gen = def.gen.map((x) => `  ${x.col.padEnd(11)} text GENERATED ALWAYS AS (data->>'${x.field}') STORED,`).join('\n');
  // Portal sessions: read only their client's rows, never write.
  let portalRead = 'app_portal_client_id() IS NULL';
  if (def.portal === 'client') portalRead = '(app_portal_client_id() IS NULL OR client_id = app_portal_client_id())';
  if (def.portal === 'self') portalRead = '(app_portal_client_id() IS NULL OR id = app_portal_client_id())';
  const idx = def.gen.map((x) => `CREATE INDEX ${t}_${x.col}_idx ON ${t} (tenant_id, ${x.col}) WHERE ${x.col} IS NOT NULL;`).join('\n');
  return `
-- ${def.name} ----------------------------------------------------------------
CREATE TABLE ${t} (
  tenant_id   uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  id          text NOT NULL CHECK (id ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$'),
  data        jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  version     bigint NOT NULL DEFAULT 1,
  change_seq  bigint NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz,
  created_by  text,
  updated_by  text,
${gen ? gen + '\n' : ''}  PRIMARY KEY (tenant_id, id)
);
CREATE INDEX ${t}_change_seq_idx ON ${t} (tenant_id, change_seq);
CREATE INDEX ${t}_created_idx ON ${t} (tenant_id, created_at DESC, id DESC);
${idx ? idx + '\n' : ''}CREATE TRIGGER ${t}_stamp BEFORE INSERT OR UPDATE ON ${t}
  FOR EACH ROW EXECUTE FUNCTION tenant_record_stamp();
ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;
ALTER TABLE ${t} FORCE ROW LEVEL SECURITY;
CREATE POLICY ${t}_tenant ON ${t}
  USING (tenant_id = app_tenant_id() AND ${portalRead})
  WITH CHECK (tenant_id = app_tenant_id() AND app_portal_client_id() IS NULL);
GRANT SELECT, INSERT, UPDATE ON ${t} TO fishtape_app;
GRANT SELECT ON ${t} TO fishtape_hq;
`;
}

export function generate() {
  const head = `-- 0003 collections: one tenant table per collection in electrical-app/js/store.js
-- (auditLog lives in audit_events). GENERATED by scripts/gen-collections-sql.js from
-- src/collections.js; do not edit by hand.
--
-- Every row: PK (tenant_id, id), body in data (jsonb), version (+1 per write),
-- change_seq (global sequence, drives sync pull), soft delete via deleted_at (tombstones
-- sync), created_by/updated_by actor strings. RLS ENABLE + FORCE on every table: rows
-- are visible and writable only when tenant_id = app.tenant_id of the transaction.

CREATE SEQUENCE change_seq AS bigint;

-- Stamps every write: serialises the tenant's writers, then takes the next change_seq
-- (so per tenant, change_seq order = commit order), bumps version, sets timestamps and
-- refuses to move a row to another tenant or id.
CREATE FUNCTION tenant_record_stamp() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
  BEGIN
    IF TG_OP = 'UPDATE' THEN
      IF NEW.tenant_id IS DISTINCT FROM OLD.tenant_id OR NEW.id IS DISTINCT FROM OLD.id THEN
        RAISE EXCEPTION 'tenant_id and id are immutable' USING ERRCODE = '42501';
      END IF;
      NEW.version := OLD.version + 1;
      NEW.created_at := OLD.created_at;
      NEW.created_by := OLD.created_by;
    ELSE
      NEW.version := 1;
      NEW.created_at := now();
    END IF;
    PERFORM pg_advisory_xact_lock(tenant_lock_key(NEW.tenant_id));
    NEW.change_seq := nextval('change_seq');
    NEW.updated_at := now();
    RETURN NEW;
  END
  $$;

GRANT USAGE ON SEQUENCE change_seq TO fishtape_app;
`;

  const tail = `
-- sync: idempotency by mutation id ----------------------------------------
CREATE TABLE sync_mutations (
  tenant_id  uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  mid        text NOT NULL CHECK (length(mid) BETWEEN 1 AND 128),
  collection text NOT NULL,
  record_id  text,
  result     jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, mid)
);
CREATE INDEX sync_mutations_created_idx ON sync_mutations (created_at);
ALTER TABLE sync_mutations ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_mutations FORCE ROW LEVEL SECURITY;
CREATE POLICY sync_mutations_tenant ON sync_mutations
  USING (tenant_id = app_tenant_id() AND app_portal_client_id() IS NULL)
  WITH CHECK (tenant_id = app_tenant_id() AND app_portal_client_id() IS NULL);
GRANT SELECT, INSERT, DELETE ON sync_mutations TO fishtape_app;

-- record history: the losing side of every last-writer-wins conflict ------
CREATE TABLE record_history (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id  uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  collection text NOT NULL,
  record_id  text NOT NULL,
  version    bigint,
  deleted    boolean NOT NULL DEFAULT false,
  data       jsonb,
  reason     text NOT NULL CHECK (reason IN ('overwritten', 'rejected')),
  mid        text,
  actor      text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX record_history_record_idx ON record_history (tenant_id, collection, record_id, id);
ALTER TABLE record_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE record_history FORCE ROW LEVEL SECURITY;
CREATE POLICY record_history_tenant ON record_history
  USING (tenant_id = app_tenant_id() AND app_portal_client_id() IS NULL)
  WITH CHECK (tenant_id = app_tenant_id() AND app_portal_client_id() IS NULL);
GRANT SELECT, INSERT ON record_history TO fishtape_app;
GRANT SELECT ON record_history, sync_mutations TO fishtape_hq;
`;
  return head + TABLE_COLLECTIONS.filter((c) => migrationOf(c) === BASE_MIGRATION).map((c) => tableSql(collectionDef(c))).join('') + tail;
}

/** A later migration: the tables of the collections whose `migration` is `name`. */
export function generateLater(name) {
  const colls = TABLE_COLLECTIONS.filter((c) => migrationOf(c) === name);
  const head = `-- ${name.slice(0, 4)} ${name.slice(5)}: tenant tables for ${colls.join(', ')}.
-- GENERATED by scripts/gen-collections-sql.js from src/collections.js; do not edit by hand.
-- Same shape, stamp trigger, RLS (ENABLE + FORCE), policy and grants as 0003_collections.sql.
`;
  return head + colls.map((c) => tableSql(collectionDef(c))).join('');
}

/** Every generated migration: [{ name, file, sql }], 0003 first. */
export function outputs() {
  const names = [...new Set(TABLE_COLLECTIONS.map(migrationOf))].sort();
  return names.map((name) => ({
    name,
    file: fileURLToPath(new URL(`../migrations/${name}.sql`, import.meta.url)),
    sql: name === BASE_MIGRATION ? generate() : generateLater(name),
  }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const o of outputs()) {
    if (process.argv.includes('--print')) process.stdout.write(o.sql);
    else { writeFileSync(o.file, o.sql); console.log(`wrote ${o.file}`); }
  }
}
